class Model:
    """The Managed API's chat endpoint. The token comes from ``token_command`` (the genai_api CLI), re-read
    when it is older than ``refresh_s`` or a call is refused; 429 / 503 are retried with backoff."""

    def __init__(self, base_url, subscription_id, token_command, model, refresh_s=600):
        self.base_url, self.sub, self.cmd, self.model, self.refresh_s = base_url.rstrip('/'), subscription_id, token_command, model, refresh_s
        self._token, self._t = None, 0

    def token(self, force=False):
        """An access token from ``token_command``, reused for ``refresh_s`` seconds (``force``: always a new one)."""
        if force or not self._token or time.time() - self._t > self.refresh_s:
            env = {k: v for k, v in os.environ.items() if k != 'PYTHONPATH'}
            r = subprocess.run(self.cmd, shell=True, capture_output=True, text=True, timeout=120, env=env)
            tok = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ''
            if not tok:
                raise RuntimeError(f'token command gave no token ({r.stderr.strip()[:200]})')
            self._token, self._t = tok, time.time()
        return self._token

    def chat(self, messages, tools):
        """One chat completion with tool calling; retries 429/503 (and a refused token) with backoff."""
        body = json.dumps({'model': self.model, 'messages': messages, 'tools': tools,
                           'max_tokens': 1200}).encode()
        for attempt in range(5):
            req = urllib.request.Request(self.base_url + '/chat/completions', data=body, method='POST', headers={
                'Content-Type': 'application/json', 'X-Subscription-ID': self.sub,
                'Authorization': 'Bearer ' + self.token(force=attempt > 0 and getattr(self, '_auth_failed', False))})
            try:
                with urllib.request.urlopen(req, timeout=120) as r:
                    return json.loads(r.read())
            except urllib.error.HTTPError as e:
                self._auth_failed = e.code in (401, 403)
                if e.code in (429, 503, 401, 403) and attempt < 4:
                    time.sleep(2 ** attempt)
                    continue
                raise RuntimeError(f'the model service answered {e.code}: {e.read()[:300].decode(errors="replace")}')
        raise RuntimeError('the model service kept refusing (429/503); try again in a minute')


def _from_env(cfg):
    """base_url / subscription_id from the settings, else as the genai_api package finds them."""
    base, sub = cfg.get('base_url'), cfg.get('subscription_id')
    a = os.environ.get('ANTHROPIC_BASE_URL', '')
    if not base:
        base = os.environ.get('GENAI_API_SERVICE_BASE_URL') or (a[:a.find('/sub-id-')] if '/sub-id-' in a else None)
    if not sub:
        sub = os.environ.get('GENAI_API_SUBSCRIPTION_ID') or (a[a.find('/sub-id-') + 8:].strip('/') if '/sub-id-' in a else None)
    return base, sub


