class _Limiter:
    def __init__(self, per_minute):
        self.n, self.t, self.lock = per_minute, [], threading.Lock()

    def ok(self):
        with self.lock:
            now = time.time()
            self.t = [x for x in self.t if now - x < 60]
            if len(self.t) >= self.n:
                return False
            self.t.append(now)
            return True


def make_handler(A, model, site_dir, settings, log):
    """The request handler: the site's files (pages with the question box added), /assistant/status and /assistant/ask."""
    limiter = _Limiter(settings['per_minute'])

    class H(SimpleHTTPRequestHandler):
        def __init__(self, *a, **kw):
            super().__init__(*a, directory=str(site_dir) if site_dir else None, **kw)

        def log_message(self, fmt, *args):            # quiet: only questions are logged
            pass

        def _json(self, code, obj):
            b = json.dumps(obj).encode()
            self.send_response(code)
            self.send_header('Content-Type', 'application/json')
            self.send_header('Content-Length', str(len(b)))
            self.end_headers()
            self.wfile.write(b)

        def do_GET(self):
            if self.path.startswith('/assistant/status'):
                return self._json(200, {'ok': True, 'offline': model is None, 'model': None if model is None else model.model,
                                        'bin_viewer': settings.get('bin_viewer'), 'notice': AI_NOTICE})
            if self.path.startswith('/assistant/widget.js'):
                return self._send(200, WIDGET.read_bytes(), 'application/javascript')
            if not site_dir:
                return self._json(404, {'error': 'no site_dir set'})
            path = urllib.parse.urlparse(self.path).path
            page = Path(self.translate_path(path))
            if page.is_dir():
                page = page / 'index.html'
            if page.suffix == '.html' and page.is_file():     # the site's page, with the question box added
                html = page.read_text(encoding='utf-8')
                tag = '<script src="/assistant/widget.js"></script>'
                html = html.replace('</body>', tag + '</body>', 1) if '</body>' in html else html + tag
                return self._send(200, html.encode('utf-8'), 'text/html; charset=utf-8')
            return super().do_GET()

        def _send(self, code, b, ctype):
            self.send_response(code)
            self.send_header('Content-Type', ctype)
            self.send_header('Content-Length', str(len(b)))
            self.send_header('Cache-Control', 'no-store')
            self.end_headers()
            self.wfile.write(b)

        def do_POST(self):
            if self.path != '/assistant/ask':
                return self._json(404, {'error': 'not found'})
            if self.headers.get('Origin') and urllib.parse.urlparse(self.headers['Origin']).hostname not in ('localhost', '127.0.0.1'):
                return self._json(403, {'error': 'only pages on this computer may ask'})
            try:
                req = json.loads(self.rfile.read(int(self.headers.get('Content-Length', 0)) or 0) or b'{}')
            except json.JSONDecodeError:
                return self._json(400, {'error': 'bad request'})
            q = (req.get('question') or '').strip()
            if not q:
                return self._json(400, {'error': 'empty question'})
            if not limiter.ok():
                return self._json(429, {'error': f'more than {settings["per_minute"]} questions in a minute; wait a little'})
            t = time.time()
            log(f'Q: {q[:300]}  view={json.dumps(req.get("view"))[:200]}')
            try:
                out = answer(A, model, q, req.get('view'), settings['max_rounds'], log)
            except Exception as e:                    # report, don't crash the server
                log(f'  ERROR {type(e).__name__}: {e}')
                return self._json(502, {'error': str(e)})
            log(f'  answered in {time.time() - t:.1f} s; {len(out["tool_calls"])} tool call(s); usage {out.get("usage")}')
            return self._json(200, out)

    return H


def cli(argv=None):
    """``ecco-insitu assistant``: run the local server, or answer one question (``--ask``)."""
    p = argparse.ArgumentParser(description='The ask-a-question prototype: a local server for the report site '
                                            '(settings: the assistant section; docs/planning/llm_assistant.md).')
    p.add_argument('--offline', action='store_true', help='no model: a fixed keyword match to one tool (for testing)')
    p.add_argument('--ask', metavar='QUESTION', help='answer one question in the terminal and exit (no server)')
    config_loader.add_arguments(p)
    a = p.parse_args(argv)
    cfg = config_loader.from_args(a)
    s = cfg['assistant']
    if not s['analysis_dir']:
        p.error('set assistant.analysis_dir (the profile-analyze folder), e.g. --set assistant.analysis_dir=...')
    A = T.Analysis(s['analysis_dir'], config_loader.get(cfg, 'paths.geodesic_bin_csv'))
    model = None
    if not a.offline:
        base, sub = _from_env(s)
        cmd = s['token_command']
        missing = [k for k, v in (('base_url', base), ('subscription_id', sub), ('token_command', cmd)) if not v]
        if missing:
            p.error('set ' + ', '.join('assistant.' + k for k in missing) + ' in config/local.yaml (or use --offline)')
        model = Model(base, sub, cmd, s['model'])
    log_dir = Path(config_loader.get(cfg, 'run.log_dir') or Path(config_loader.CONFIG_DIR).parent / 'z_logs')
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / f'assistant_{time.strftime("%Y%m%d")}.log'

    def log(msg):
        line = f'{time.strftime("%H:%M:%S")} {msg}'
        print(line, flush=True)
        with open(log_path, 'a') as f:
            f.write(line + '\n')

    if a.ask:
        out = answer(A, model, a.ask, None, s['max_rounds'], log)
        print('\n' + out['answer'] + '\n')
        for v in out['views']:
            print(f'  [{v["page"]}] {v["caption"]}: ?{urllib.parse.urlencode(v["params"])}')
        print('\n' + out['notice'])
        return 0
    site = Path(s['site_dir']) if s['site_dir'] else None
    srv = ThreadingHTTPServer(('127.0.0.1', s['port']), make_handler(A, model, site, s, log))
    log(f'assistant on http://localhost:{s["port"]}/ ({"offline" if model is None else model.model}); '
        f'site {site}; analysis {A.dir}; questions logged to {log_path}. Ctrl-C stops it.')
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == '__main__':
    sys.exit(cli())
