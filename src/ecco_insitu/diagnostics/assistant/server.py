def _view_text(view):
    if not view:
        return 'The user is on the questions page (no current view).'
    keep = {k: v for k, v in view.items() if k in ('page', 'src', 'ct', 'V', 'part', 'depth', 'years', 'an', 'band', 'ref', 'k')}
    return 'The page\'s current view: ' + json.dumps(keep)


def answer(A, model, question, view=None, max_rounds=6, log=None):
    """{'answer', 'views', 'tool_calls', 'notice'}; ``model`` None = offline."""
    if model is None:
        return _offline(A, question, view)
    messages = [{'role': 'system', 'content': SYSTEM + '\n\n' + _view_text(view)},
                {'role': 'user', 'content': question[:2000]}]
    views, calls = [], []
    for _ in range(max_rounds):
        r = model.chat(messages, T.SCHEMAS)
        msg = r['choices'][0]['message']
        tc = msg.get('tool_calls') or []
        messages.append({k: v for k, v in msg.items() if k in ('role', 'content', 'tool_calls') and v is not None})
        if not tc:
            return {'answer': (msg.get('content') or '').strip(), 'views': _dedupe(views), 'tool_calls': calls,
                    'notice': AI_NOTICE, 'usage': r.get('usage')}
        for c in tc:
            name = c['function']['name']
            try:
                args = json.loads(c['function'].get('arguments') or '{}')
            except json.JSONDecodeError:
                args = {}
            res, vs = T.call(A, name, args)
            calls.append({'tool': name, 'args': args, 'error': res.get('error') if isinstance(res, dict) else None})
            views += vs
            if log:
                log(f'  tool {name} {json.dumps(args)} -> {json.dumps(res)[:160]}')
            messages.append({'role': 'tool', 'tool_call_id': c['id'], 'content': json.dumps(res)})
    return {'answer': 'I could not finish within the allowed number of steps; try a narrower question.',
            'views': _dedupe(views), 'tool_calls': calls, 'notice': AI_NOTICE}


def _dedupe(views):
    seen, out = set(), []
    for v in views:
        key = json.dumps([v['page'], v['params']], sort_keys=True)
        if key not in seen:
            seen.add(key); out.append(v)
    return out[:6]


def _offline(A, question, view):
    """No model: a fixed keyword match to one tool, so the page, links and tools can be tested."""
    q, view = question.lower(), view or {}
    src = next((s for s in A.sources if s.lower() in q), view.get('src') or ('PFL' if 'PFL' in A.sources else A.sources[0]))
    ct = 'vs_clim' if 'clim' in q else 'vs_model' if 'model' in q else view.get('ct') or ('vs_model' if 'vs_model' in A.cost_types else A.cost_types[0])
    V = 'S' if re.search(r'\bsalin|\bS\b', question) else 'T'
    nums = [float(x) for x in re.findall(r'(\d{2,4})\s*m\b', q)]
    z0, z1 = (min(nums), max(nums)) if len(nums) >= 2 else (nums[0], nums[0]) if nums else (0, 2000)
    if 'peak' in q or 'bump' in q or 'spike' in q:
        name, args = 'peak_attribution', dict(src=src, cost_type=ct, variable=V, part='mean', depth_from=z0, depth_to=z1 if z1 > z0 else z0 + 600)
    elif 'where' in q:
        name, args = 'where_high', dict(src=src, cost_type=ct, variable=V, depth_from=z0, depth_to=z1)
    elif 'time' in q or 'year' in q or 'trend' in q:
        name, args = 'cost_vs_time', dict(src=src, cost_type=ct, variable=V)
    elif 'class' in q or 'compare' in q:
        name, args = 'compare_classes', dict(cost_type=ct, variable=V, depth_from=z0, depth_to=z1)
    elif 'offset' in q or 'steady' in q:
        name, args = 'offset_vs_variability', dict(src=src, cost_type=ct, variable=V, depth_from=z0, depth_to=z1)
    else:
        name, args = 'cost_vs_depth', dict(src=src, cost_type=ct, variable=V)
    res, vs = T.call(A, name, args)
    return {'answer': f'(offline test mode: no model; ran {name} with {json.dumps(args)})\n' + json.dumps(res, indent=1)[:1500],
            'views': _dedupe(vs), 'tool_calls': [{'tool': name, 'args': args}], 'notice': 'Offline test mode: no AI.'}


