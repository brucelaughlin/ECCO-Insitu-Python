"""
``ecco-insitu assistant``: the ask-a-question prototype. A small local web server that

- serves the report site (``assistant.site_dir``) on http://localhost:<port>/, adding the question box
  (widget.js) to each page as it is served (the files, and the published site, are unchanged);
- answers ``POST /ask`` {"question", "view"}: sends the question to the JPL GenAI Managed API (OpenAI chat format,
  tool calling) with the tools of :mod:`tools`, runs the tools the model picks on the analysis
  (``assistant.analysis_dir``), and returns the model's short answer with links to the views behind every number.

The credential stays here: the page never sees it. Only the question, the page's current view and the tools'
summary numbers go to the model; no data. ``--offline`` answers without a model (a fixed keyword match to one
tool), to test everything else. Settings: the ``assistant`` section of the settings (src/ecco_insitu/defaults.yaml);
switching subscription (e.g. Individual -> Application) is a settings change only. Plan:
docs/planning/llm_assistant.md.
"""
